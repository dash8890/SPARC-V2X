function out = wilab_closed_loop_packet_accounting(op, varargin)
% Payload-faithful per-packet delivery accounting for the closed-loop bridge.
%
% WiLabV2Xsim keeps stationManagement.pckBuffer as a per-vehicle *count* of
% queued packets.  It does not attach an identity to those packets, so the
% legacy bridge could only observe "some packet from this source was received
% in this interval".  That is the first-packet completion bug.
%
% This helper maintains a parallel FIFO of packet tags for every vehicle.
% The FIFO mirrors the order in which packets enter pckBuffer:
%
%   * a beacon generated by the application layer is tagged 0;
%   * the q-th packet of task k is tagged  (k+1)*BASE + q + 1,  q = 0..n_k-1.
%
% Packets are admitted through a *pending* queue rather than being dumped into
% pckBuffer.  'pace' moves at most one unit per source into pckBuffer when the
% source's next Mode-2 reservation occurs before the next safety beacon.  This
% prevents the single-packet queue from overflowing and keeps the packet
% stream physically paced at the configured reservation rate.
%
% When a packet finishes its last replica its reception state is still in
% stationManagement.pckReceived at the beginning of the following TTI.  The
% 'capture' operation reads that state before WiLab resets pckReceived, pops
% the head tag, and credits the corresponding payload unit exactly once.  A
% missing unit is retried (bounded attempts) until the absolute deadline;
% a completed/cancelled task is removed from the pending and in-flight queues.
%
% Operations
%   'push_beacon', id
%   'register',   action, stationManagement, now_s
%   'pace',       stationManagement, timeManagement, appParams, phyParams, now_s
%   'mark_final', ids            (packets whose last replica was sent)
%   'capture',    stationManagement, timeNow, epoch
%   'reconcile',  stationManagement, timeNow
%   'state'                      -> struct array for the result JSON
%
% Persistent state lives in the WILAB_CLOSED_LOOP global so that the vendor
% simulator does not have to be modified.

global WILAB_CLOSED_LOOP;
if isempty(WILAB_CLOSED_LOOP), WILAB_CLOSED_LOOP = struct(); end

BASE = 100000;                 % tag base; supports up to 100k payload units per task
MAX_ATTEMPTS = 3;              % bounded retransmissions per payload unit
RETRY_BACKOFF_S = 0.02;        % one 20 ms controller epoch

if ~isfield(WILAB_CLOSED_LOOP,'pkt_queue')
    WILAB_CLOSED_LOOP.pkt_queue = {};
    WILAB_CLOSED_LOOP.fate_pending = false(0,1);
    WILAB_CLOSED_LOOP.task_required = zeros(0,1);
    WILAB_CLOSED_LOOP.task_received = zeros(0,1);
    WILAB_CLOSED_LOOP.task_helper = zeros(0,1);
    WILAB_CLOSED_LOOP.task_source = zeros(0,1);
    WILAB_CLOSED_LOOP.task_rx_bits = false(0,1);
    WILAB_CLOSED_LOOP.task_complete_epoch = nan(0,1);
    WILAB_CLOSED_LOOP.task_complete_time = nan(0,1);
    WILAB_CLOSED_LOOP.pkt_overflow_losses = 0;
    WILAB_CLOSED_LOOP.pkt_tag_deficits = 0;
    WILAB_CLOSED_LOOP.pkt_capture_missing = 0;
    WILAB_CLOSED_LOOP.pkt_units_credited = 0;
    WILAB_CLOSED_LOOP.pkt_units_duplicate = 0;
end
if ~isfield(WILAB_CLOSED_LOOP,'pending')
    WILAB_CLOSED_LOOP.pending = {};
    WILAB_CLOSED_LOOP.pending_not_before = {};
    WILAB_CLOSED_LOOP.pending_attempts = {};
    WILAB_CLOSED_LOOP.task_pending_bits = false(0,1);
    WILAB_CLOSED_LOOP.task_unit_attempts = zeros(0,1);
    WILAB_CLOSED_LOOP.task_cancelled = false(0,1);
    WILAB_CLOSED_LOOP.task_deadline_s = nan(0,1);
    WILAB_CLOSED_LOOP.task_release_s = nan(0,1);
    WILAB_CLOSED_LOOP.pkt_paced = 0;
    WILAB_CLOSED_LOOP.pkt_retransmitted = 0;
    WILAB_CLOSED_LOOP.pkt_cancelled = 0;
    WILAB_CLOSED_LOOP.pkt_dropped = 0;
end

out = [];
switch lower(op)
    case 'push_beacon'
        id = round(double(varargin{1}));
        if id < 1, return; end
        WILAB_CLOSED_LOOP.pkt_queue = ensure_cell(WILAB_CLOSED_LOOP.pkt_queue, id);
        WILAB_CLOSED_LOOP.pkt_queue{id}(end+1) = 0;

    case 'register'
        out = register_assignments(varargin{1}, varargin{2}, varargin{3}, BASE);

    case 'pace'
        out = pace_queue(varargin{1}, varargin{2}, varargin{3}, varargin{4}, ...
            varargin{5}, BASE);

    case 'mark_final'
        ids = round(double(varargin{1}(:)));
        if isempty(ids), return; end
        WILAB_CLOSED_LOOP.fate_pending = ensure_vec(WILAB_CLOSED_LOOP.fate_pending, max(ids), false);
        WILAB_CLOSED_LOOP.fate_pending(ids) = true;

    case 'capture'
        capture_final(varargin{1}, varargin{2}, varargin{3}, BASE);

    case 'reconcile'
        reconcile_queue(varargin{1}, varargin{2}, BASE);

    case 'state'
        out = task_state();
end
end

% -------------------------------------------------------------------------
function stationManagement = register_assignments(action, stationManagement, now_s, BASE)
global WILAB_CLOSED_LOOP;
if isempty(action) || ~isstruct(action) || ~isfield(action,'assignments')
    return;
end
A = action.assignments;
if isempty(A), return; end
if iscell(A)
    A = [A{:}];
end
for j = 1:numel(A)
    tid = round(double(A(j).task_id));
    % The Python action carries the resolved WiLab vehicle IDs.  Fall back to
    % the legacy zero-based +1 mapping only when the field is absent.
    if isfield(A(j),'source_wilab_id') && ~isempty(A(j).source_wilab_id) && ...
            double(A(j).source_wilab_id) >= 1
        sid = round(double(A(j).source_wilab_id));
    else
        sid = round(double(A(j).source_id)) + 1;
    end
    if isfield(A(j),'helper_wilab_id') && ~isempty(A(j).helper_wilab_id) && ...
            double(A(j).helper_wilab_id) >= 1
        hid = round(double(A(j).helper_wilab_id));
    else
        hid = round(double(A(j).helper_id)) + 1;
    end
    if isfield(A(j),'packet_count') && ~isempty(A(j).packet_count)
        req = round(double(A(j).packet_count));
    elseif isfield(A(j),'payload_required') && ~isempty(A(j).payload_required)
        req = round(double(A(j).payload_required));
    else
        req = 1;
    end
    if tid < 0 || sid < 1 || hid < 1 || req <= 0, continue; end
    if req >= BASE
        error('wilab_closed_loop_packet_accounting:packetCount', ...
            'packet_count %d exceeds tag capacity %d', req, BASE-1);
    end
    idx = tid + 1;
    WILAB_CLOSED_LOOP.task_required = ensure_vec(WILAB_CLOSED_LOOP.task_required, idx, 0);
    WILAB_CLOSED_LOOP.task_received = ensure_vec(WILAB_CLOSED_LOOP.task_received, idx, 0);
    WILAB_CLOSED_LOOP.task_helper = ensure_vec(WILAB_CLOSED_LOOP.task_helper, idx, 0);
    WILAB_CLOSED_LOOP.task_source = ensure_vec(WILAB_CLOSED_LOOP.task_source, idx, 0);
    WILAB_CLOSED_LOOP.task_complete_epoch = ensure_vec(WILAB_CLOSED_LOOP.task_complete_epoch, idx, NaN);
    WILAB_CLOSED_LOOP.task_complete_time = ensure_vec(WILAB_CLOSED_LOOP.task_complete_time, idx, NaN);
    WILAB_CLOSED_LOOP.task_cancelled = ensure_vec(WILAB_CLOSED_LOOP.task_cancelled, idx, false);
    WILAB_CLOSED_LOOP.task_deadline_s = ensure_vec(WILAB_CLOSED_LOOP.task_deadline_s, idx, NaN);
    WILAB_CLOSED_LOOP.task_release_s = ensure_vec(WILAB_CLOSED_LOOP.task_release_s, idx, NaN);
    ncol = size(WILAB_CLOSED_LOOP.task_rx_bits, 2);
    if size(WILAB_CLOSED_LOOP.task_rx_bits,1) < idx
        WILAB_CLOSED_LOOP.task_rx_bits(idx, max(1,ncol)) = false;
    end
    if size(WILAB_CLOSED_LOOP.task_rx_bits,2) < req
        WILAB_CLOSED_LOOP.task_rx_bits(:, end+1:req) = false;
    end
    if size(WILAB_CLOSED_LOOP.task_pending_bits,1) < idx
        WILAB_CLOSED_LOOP.task_pending_bits(idx, max(1,size(WILAB_CLOSED_LOOP.task_pending_bits,2))) = false;
    end
    if size(WILAB_CLOSED_LOOP.task_pending_bits,2) < req
        WILAB_CLOSED_LOOP.task_pending_bits(:, end+1:req) = false;
    end
    if size(WILAB_CLOSED_LOOP.task_unit_attempts,1) < idx
        WILAB_CLOSED_LOOP.task_unit_attempts(idx, max(1,size(WILAB_CLOSED_LOOP.task_unit_attempts,2))) = 0;
    end
    if size(WILAB_CLOSED_LOOP.task_unit_attempts,2) < req
        WILAB_CLOSED_LOOP.task_unit_attempts(:, end+1:req) = 0;
    end

    % Python absolute times are relative to controller epoch 0, which may be
    % later than WiLab time 0 because of warm-up.
    if isfield(WILAB_CLOSED_LOOP,'controllerStartTime')
        clock0 = double(WILAB_CLOSED_LOOP.controllerStartTime);
    else
        clock0 = 0.0;
    end
    if isfield(A(j),'deadline_s') && ~isempty(A(j).deadline_s) && isfinite(double(A(j).deadline_s))
        deadline_s = clock0 + double(A(j).deadline_s);
    else
        deadline_s = now_s + double(A(j).deadline_ms) / 1000.0;
    end
    if isfield(A(j),'release_ms') && ~isempty(A(j).release_ms)
        release_s = clock0 + double(A(j).release_ms) / 1000.0;
    else
        release_s = now_s;
    end

    % A task keeps the required count it was first admitted with.  Later
    % re-injections retransmit the same units, they do not enlarge the task.
    if WILAB_CLOSED_LOOP.task_required(idx) == 0
        WILAB_CLOSED_LOOP.task_required(idx) = req;
        WILAB_CLOSED_LOOP.task_source(idx) = sid;
        WILAB_CLOSED_LOOP.task_helper(idx) = hid;
        WILAB_CLOSED_LOOP.task_deadline_s(idx) = deadline_s;
        WILAB_CLOSED_LOOP.task_release_s(idx) = release_s;
        WILAB_CLOSED_LOOP.task_cancelled(idx) = false;
        WILAB_CLOSED_LOOP.task_rx_bits(idx, 1:req) = false;
        WILAB_CLOSED_LOOP.task_pending_bits(idx, 1:req) = false;
        WILAB_CLOSED_LOOP.task_unit_attempts(idx, 1:req) = 0;
    elseif WILAB_CLOSED_LOOP.task_helper(idx) ~= hid && ...
            isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx)) && ...
            ~WILAB_CLOSED_LOOP.task_cancelled(idx)
        % Helper swap: the payload must now reach the new helper.  Flush the
        % source queue for this task so in-flight packets addressed to the old
        % helper cannot be credited to the new one, then reset the unit bitmap.
        stationManagement = flush_task_queue(idx, sid, stationManagement, BASE);
        flush_task_pending(idx, sid, BASE);
        WILAB_CLOSED_LOOP.task_helper(idx) = hid;
        WILAB_CLOSED_LOOP.task_received(idx) = 0;
        WILAB_CLOSED_LOOP.task_rx_bits(idx, :) = false;
        WILAB_CLOSED_LOOP.task_pending_bits(idx, :) = false;
        WILAB_CLOSED_LOOP.task_unit_attempts(idx, :) = 0;
    end

    if WILAB_CLOSED_LOOP.task_cancelled(idx) || ...
            ~isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx))
        continue;
    end

    WILAB_CLOSED_LOOP.pending = ensure_cell(WILAB_CLOSED_LOOP.pending, sid);
    WILAB_CLOSED_LOOP.pending_not_before = ensure_cell(WILAB_CLOSED_LOOP.pending_not_before, sid);
    WILAB_CLOSED_LOOP.pending_attempts = ensure_cell(WILAB_CLOSED_LOOP.pending_attempts, sid);
    WILAB_CLOSED_LOOP.pkt_queue = ensure_cell(WILAB_CLOSED_LOOP.pkt_queue, sid);
    in_flight = WILAB_CLOSED_LOOP.pkt_queue{sid};

    for u = 0:req-1
        if WILAB_CLOSED_LOOP.task_rx_bits(idx, u+1)
            continue;
        end
        if WILAB_CLOSED_LOOP.task_pending_bits(idx, u+1)
            continue;
        end
        tag = tid*BASE + u + 1;
        if any(in_flight == tag)
            continue;   % already in the WiLab queue / in service
        end
        WILAB_CLOSED_LOOP.pending{sid}(end+1) = tag;
        WILAB_CLOSED_LOOP.pending_not_before{sid}(end+1) = now_s;
        WILAB_CLOSED_LOOP.pending_attempts{sid}(end+1) = 0;
        WILAB_CLOSED_LOOP.task_pending_bits(idx, u+1) = true;
    end
end
end

% -------------------------------------------------------------------------
function stationManagement = pace_queue(stationManagement, timeManagement, appParams, phyParams, now_s, BASE)
global WILAB_CLOSED_LOOP;
if ~isfield(stationManagement,'pckBuffer'), return; end
expire_tasks(now_s);
nbuf = numel(stationManagement.pckBuffer);
WILAB_CLOSED_LOOP.pending = ensure_cell(WILAB_CLOSED_LOOP.pending, nbuf);
WILAB_CLOSED_LOOP.pending_not_before = ensure_cell(WILAB_CLOSED_LOOP.pending_not_before, nbuf);
WILAB_CLOSED_LOOP.pending_attempts = ensure_cell(WILAB_CLOSED_LOOP.pending_attempts, nbuf);
WILAB_CLOSED_LOOP.pkt_queue = ensure_cell(WILAB_CLOSED_LOOP.pkt_queue, nbuf);

for sid = 1:nbuf
    [tags, tnot, tatt] = filter_pending(sid, BASE);
    WILAB_CLOSED_LOOP.pending{sid} = tags;
    WILAB_CLOSED_LOOP.pending_not_before{sid} = tnot;
    WILAB_CLOSED_LOOP.pending_attempts{sid} = tatt;
    if isempty(tags), continue; end
    if stationManagement.pckBuffer(sid) >= 1, continue; end
    if ~isfield(stationManagement,'BRid') || sid > size(stationManagement.BRid,1) || ...
            stationManagement.BRid(sid,1) <= 0
        continue;
    end
    t_res = next_reservation_s(sid, stationManagement, timeManagement, appParams, phyParams);
    if isempty(t_res)
        continue;
    end
    % Never inject when the next reservation is at/after the next safety
    % beacon: the beacon would make pckBuffer 2 before the computation packet
    % is served, and WiLab's single-packet queue would discard one of them.
    if isfield(timeManagement,'timeNextPacket') && numel(timeManagement.timeNextPacket) >= sid
        t_beacon = double(timeManagement.timeNextPacket(sid));
        if t_beacon - now_s <= 1e-9 || t_res >= t_beacon - 1e-9
            continue;
        end
    end
    eligible = find(tnot <= now_s + 1e-12, 1, 'first');
    if isempty(eligible), continue; end
    tag = tags(eligible);
    attempts = tatt(eligible);
    tags(eligible) = [];
    tnot(eligible) = [];
    tatt(eligible) = [];
    WILAB_CLOSED_LOOP.pending{sid} = tags;
    WILAB_CLOSED_LOOP.pending_not_before{sid} = tnot;
    WILAB_CLOSED_LOOP.pending_attempts{sid} = tatt;

    stationManagement.pckBuffer(sid) = stationManagement.pckBuffer(sid) + 1;
    stationManagement.pckNextAttempt(sid) = 1;
    WILAB_CLOSED_LOOP.pkt_queue{sid}(end+1) = tag;
    WILAB_CLOSED_LOOP.pkt_paced = WILAB_CLOSED_LOOP.pkt_paced + 1;
    if attempts > 0
        WILAB_CLOSED_LOOP.pkt_retransmitted = WILAB_CLOSED_LOOP.pkt_retransmitted + 1;
    end
    idx = floor((tag-1)/BASE) + 1;
    unit = mod(tag-1, BASE) + 1;
    if idx >= 1 && idx <= size(WILAB_CLOSED_LOOP.task_pending_bits,1) && ...
            unit >= 1 && unit <= size(WILAB_CLOSED_LOOP.task_pending_bits,2)
        WILAB_CLOSED_LOOP.task_pending_bits(idx, unit) = false;
    end
end
end

% -------------------------------------------------------------------------
function t_res = next_reservation_s(sid, stationManagement, timeManagement, appParams, phyParams)
% Absolute time (s) of the next TTI in which this source's current BR column
% is scheduled.  The Mode-2 reservation repeats every appParams.NbeaconsT TTIs.
t_res = [];
if ~isfield(stationManagement,'BRid') || sid > size(stationManagement.BRid,1)
    return;
end
attempt = 1;
if isfield(stationManagement,'pckNextAttempt')
    ncol = max(1, size(stationManagement.BRid,2));
    attempt = mod(round(double(stationManagement.pckNextAttempt(sid)))-1, ncol) + 1;
end
br = double(stationManagement.BRid(sid, attempt));
if br <= 0 || appParams.NbeaconsF <= 0 || appParams.NbeaconsT <= 0
    return;
end
slot = ceil(br / appParams.NbeaconsF);
currentT = mod(double(timeManagement.elapsedTime_TTIs) - 1, appParams.NbeaconsT) + 1;
delta = mod(slot - currentT, appParams.NbeaconsT);
t_res = double(timeManagement.timeNow) + double(phyParams.TTI) * delta;
end

% -------------------------------------------------------------------------
function expire_tasks(now_s)
global WILAB_CLOSED_LOOP;
n = numel(WILAB_CLOSED_LOOP.task_required);
for idx = 1:n
    if WILAB_CLOSED_LOOP.task_required(idx) <= 0, continue; end
    if WILAB_CLOSED_LOOP.task_cancelled(idx), continue; end
    if ~isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx)), continue; end
    dl = WILAB_CLOSED_LOOP.task_deadline_s(idx);
    if isfinite(dl) && now_s > dl + 1e-9
        WILAB_CLOSED_LOOP.task_cancelled(idx) = true;
    end
end
end

% -------------------------------------------------------------------------
function [tags, tnot, tatt] = filter_pending(sid, BASE)
% Drop pending tags for completed/cancelled tasks.  A tag whose task is not
% registered yet is left alone (it may be a beacon or a legacy packet).
global WILAB_CLOSED_LOOP;
tags = WILAB_CLOSED_LOOP.pending{sid};
tnot = WILAB_CLOSED_LOOP.pending_not_before{sid};
tatt = WILAB_CLOSED_LOOP.pending_attempts{sid};
if isempty(tags), return; end
keep = true(size(tags));
for k = 1:numel(tags)
    tag = tags(k);
    if tag <= 0, continue; end
    idx = floor((tag-1)/BASE) + 1;
    unit = mod(tag-1, BASE) + 1;
    if idx > numel(WILAB_CLOSED_LOOP.task_required) || ...
            WILAB_CLOSED_LOOP.task_required(idx) <= 0
        keep(k) = false;
        continue;
    end
    if WILAB_CLOSED_LOOP.task_cancelled(idx) || ...
            ~isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx))
        keep(k) = false;
        WILAB_CLOSED_LOOP.pkt_cancelled = WILAB_CLOSED_LOOP.pkt_cancelled + 1;
        if idx <= size(WILAB_CLOSED_LOOP.task_pending_bits,1) && ...
                unit <= size(WILAB_CLOSED_LOOP.task_pending_bits,2)
            WILAB_CLOSED_LOOP.task_pending_bits(idx, unit) = false;
        end
    end
end
tags = tags(keep);
tnot = tnot(keep);
tatt = tatt(keep);
end

% -------------------------------------------------------------------------
function capture_final(stationManagement, timeNow, epoch, BASE)
global WILAB_CLOSED_LOOP;
MAX_ATTEMPTS = 3;
RETRY_BACKOFF_S = 0.02;
ids = find(WILAB_CLOSED_LOOP.fate_pending);
for ii = 1:numel(ids)
    id = ids(ii);
    WILAB_CLOSED_LOOP.fate_pending(id) = false;
    if id > numel(WILAB_CLOSED_LOOP.pkt_queue) || isempty(WILAB_CLOSED_LOOP.pkt_queue{id})
        WILAB_CLOSED_LOOP.pkt_capture_missing = ...
            WILAB_CLOSED_LOOP.pkt_capture_missing + 1;
        continue;
    end
    q = WILAB_CLOSED_LOOP.pkt_queue{id};
    tag = q(1);
    WILAB_CLOSED_LOOP.pkt_queue{id} = q(2:end);
    if tag <= 0, continue; end                     % beacon or unknown
    if ~isfield(stationManagement,'pckReceived'), continue; end
    if id > size(stationManagement.pckReceived,2), continue; end
    tid = floor((tag-1)/BASE);
    unit = mod(tag-1, BASE);
    if tid < 0 || tid+1 > numel(WILAB_CLOSED_LOOP.task_required), continue; end
    idx = tid + 1;
    if unit < 0 || unit+1 > size(WILAB_CLOSED_LOOP.task_rx_bits,2), continue; end
    if WILAB_CLOSED_LOOP.task_cancelled(idx) || ...
            ~isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx))
        WILAB_CLOSED_LOOP.task_pending_bits(idx, unit+1) = false;
        continue;
    end
    helper = WILAB_CLOSED_LOOP.task_helper(idx);
    if helper < 1 || helper > size(stationManagement.pckReceived,1)
        continue;
    end
    rx = stationManagement.pckReceived(helper, id);
    if rx <= 0
        % Outstanding unit: retry it, bounded, until the absolute deadline.
        attempts = WILAB_CLOSED_LOOP.task_unit_attempts(idx, unit+1) + 1;
        WILAB_CLOSED_LOOP.task_unit_attempts(idx, unit+1) = attempts;
        dl = WILAB_CLOSED_LOOP.task_deadline_s(idx);
        can_retry = attempts <= MAX_ATTEMPTS && ...
            (isnan(dl) || (timeNow + RETRY_BACKOFF_S <= dl + 1e-9));
        if can_retry
            WILAB_CLOSED_LOOP.pending = ensure_cell(WILAB_CLOSED_LOOP.pending, id);
            WILAB_CLOSED_LOOP.pending_not_before = ensure_cell(WILAB_CLOSED_LOOP.pending_not_before, id);
            WILAB_CLOSED_LOOP.pending_attempts = ensure_cell(WILAB_CLOSED_LOOP.pending_attempts, id);
            WILAB_CLOSED_LOOP.pending{id}(end+1) = tag;
            WILAB_CLOSED_LOOP.pending_not_before{id}(end+1) = timeNow + RETRY_BACKOFF_S;
            WILAB_CLOSED_LOOP.pending_attempts{id}(end+1) = attempts;
            WILAB_CLOSED_LOOP.task_pending_bits(idx, unit+1) = true;
        else
            WILAB_CLOSED_LOOP.pkt_dropped = WILAB_CLOSED_LOOP.pkt_dropped + 1;
            WILAB_CLOSED_LOOP.task_pending_bits(idx, unit+1) = false;
        end
        continue;
    end
    WILAB_CLOSED_LOOP.task_pending_bits(idx, unit+1) = false;
    WILAB_CLOSED_LOOP.task_unit_attempts(idx, unit+1) = 0;
    if WILAB_CLOSED_LOOP.task_rx_bits(idx, unit+1)
        WILAB_CLOSED_LOOP.pkt_units_duplicate = ...
            WILAB_CLOSED_LOOP.pkt_units_duplicate + 1;
        continue;                                   % deduplicate payload unit
    end
    WILAB_CLOSED_LOOP.task_rx_bits(idx, unit+1) = true;
    WILAB_CLOSED_LOOP.task_received(idx) = ...
        WILAB_CLOSED_LOOP.task_received(idx) + 1;
    WILAB_CLOSED_LOOP.pkt_units_credited = ...
        WILAB_CLOSED_LOOP.pkt_units_credited + 1;
    req = WILAB_CLOSED_LOOP.task_required(idx);
    if req > 0 && WILAB_CLOSED_LOOP.task_received(idx) >= req && ...
            isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx))
        WILAB_CLOSED_LOOP.task_complete_epoch(idx) = double(epoch);
        WILAB_CLOSED_LOOP.task_complete_time(idx) = double(timeNow);
    end
end
end

% -------------------------------------------------------------------------
function reconcile_queue(stationManagement, now_s, BASE)
% pckBuffer also shrinks when WiLab overflows a queue (bufferOverflowLTE) or
% when a vehicle leaves.  WiLab's overflow discards the newest packet, so the
% FIFO drops its tail.  A task tag dropped this way is outstanding payload:
% put it back in the pending queue (bounded) rather than silently losing it.
global WILAB_CLOSED_LOOP;
if ~isfield(stationManagement,'pckBuffer'), return; end
buf = stationManagement.pckBuffer;
WILAB_CLOSED_LOOP.pkt_queue = ensure_cell(WILAB_CLOSED_LOOP.pkt_queue, numel(buf));
for id = 1:numel(buf)
    nb = max(0, round(double(buf(id))));
    q = WILAB_CLOSED_LOOP.pkt_queue{id};
    nq = numel(q);
    if nq > nb
        dropped = q(nb+1:end);
        WILAB_CLOSED_LOOP.pkt_overflow_losses = ...
            WILAB_CLOSED_LOOP.pkt_overflow_losses + (nq - nb);
        WILAB_CLOSED_LOOP.pkt_queue{id} = q(1:nb);
        for k = 1:numel(dropped)
            requeue_tag(dropped(k), id, now_s, BASE);
        end
    elseif nq < nb
        WILAB_CLOSED_LOOP.pkt_tag_deficits = ...
            WILAB_CLOSED_LOOP.pkt_tag_deficits + (nb - nq);
        WILAB_CLOSED_LOOP.pkt_queue{id} = [q, zeros(1, nb-nq)];
    end
end
end

% -------------------------------------------------------------------------
function requeue_tag(tag, sid, now_s, BASE)
global WILAB_CLOSED_LOOP;
RETRY_BACKOFF_S = 0.02;
if tag <= 0, return; end
idx = floor((tag-1)/BASE) + 1;
unit = mod(tag-1, BASE) + 1;
if idx < 1 || idx > numel(WILAB_CLOSED_LOOP.task_required), return; end
if WILAB_CLOSED_LOOP.task_required(idx) <= 0, return; end
if WILAB_CLOSED_LOOP.task_cancelled(idx) || ...
        ~isnan(WILAB_CLOSED_LOOP.task_complete_epoch(idx))
    return;
end
if WILAB_CLOSED_LOOP.task_rx_bits(idx, unit)
    return;
end
WILAB_CLOSED_LOOP.pending = ensure_cell(WILAB_CLOSED_LOOP.pending, sid);
WILAB_CLOSED_LOOP.pending_not_before = ensure_cell(WILAB_CLOSED_LOOP.pending_not_before, sid);
WILAB_CLOSED_LOOP.pending_attempts = ensure_cell(WILAB_CLOSED_LOOP.pending_attempts, sid);
WILAB_CLOSED_LOOP.pending{sid}(end+1) = tag;
WILAB_CLOSED_LOOP.pending_not_before{sid}(end+1) = now_s + RETRY_BACKOFF_S;
WILAB_CLOSED_LOOP.pending_attempts{sid}(end+1) = ...
    WILAB_CLOSED_LOOP.task_unit_attempts(idx, unit) + 1;
WILAB_CLOSED_LOOP.task_pending_bits(idx, unit) = true;
end

% -------------------------------------------------------------------------
function stationManagement = flush_task_queue(idx, sid, stationManagement, BASE)
% Remove this task's tags from the source's in-flight queue after a helper
% swap.  The PHY may still transmit the physical packet, but it can no longer
% be credited to the new helper.
global WILAB_CLOSED_LOOP;
if ~isfield(stationManagement,'pckBuffer') || sid > numel(stationManagement.pckBuffer)
    return;
end
WILAB_CLOSED_LOOP.pkt_queue = ensure_cell(WILAB_CLOSED_LOOP.pkt_queue, sid);
q = WILAB_CLOSED_LOOP.pkt_queue{sid};
if isempty(q), return; end
req = WILAB_CLOSED_LOOP.task_required(idx);
tid = idx - 1;
tags = tid*BASE + (0:req-1) + 1;
remove = ismember(q, tags);
if any(remove)
    WILAB_CLOSED_LOOP.pkt_queue{sid} = q(~remove);
    stationManagement.pckBuffer(sid) = max(0, stationManagement.pckBuffer(sid) - sum(remove));
end
end

% -------------------------------------------------------------------------
function flush_task_pending(idx, sid, BASE)
% Remove this task's units from the source's pending queue.  Used on a helper
% swap before all still-required units are re-enqueued for the new helper.
global WILAB_CLOSED_LOOP;
WILAB_CLOSED_LOOP.pending = ensure_cell(WILAB_CLOSED_LOOP.pending, sid);
WILAB_CLOSED_LOOP.pending_not_before = ensure_cell(WILAB_CLOSED_LOOP.pending_not_before, sid);
WILAB_CLOSED_LOOP.pending_attempts = ensure_cell(WILAB_CLOSED_LOOP.pending_attempts, sid);
tags = WILAB_CLOSED_LOOP.pending{sid};
if isempty(tags), return; end
tid = idx - 1;
task_tags = tid*BASE + (0:WILAB_CLOSED_LOOP.task_required(idx)-1) + 1;
keep = ~ismember(tags, task_tags);
WILAB_CLOSED_LOOP.pending{sid} = tags(keep);
WILAB_CLOSED_LOOP.pending_not_before{sid} = WILAB_CLOSED_LOOP.pending_not_before{sid}(keep);
WILAB_CLOSED_LOOP.pending_attempts{sid} = WILAB_CLOSED_LOOP.pending_attempts{sid}(keep);
end

% -------------------------------------------------------------------------
function out = task_state()
global WILAB_CLOSED_LOOP;
req = WILAB_CLOSED_LOOP.task_required(:);
n = numel(req);
active = find(req > 0);
if isempty(active)
    out = struct([]);
    return;
end
out = repmat(struct('task_id',0,'source_id',0,'helper_id',0, ...
    'required_packets',0,'received_packets',0,'complete',false, ...
    'complete_epoch',[],'complete_time_s',[], ...
    'overflow_losses',0,'tag_deficits',0,'capture_missing',0, ...
    'cancelled',false,'pending_units',0,'deadline_s',[], ...
    'paced_packets',0,'retransmitted_packets',0,'cancelled_packets',0, ...
    'dropped_packets',0), numel(active), 1);
for k = 1:numel(active)
    i = active(k);
    out(k).task_id = i-1;
    out(k).source_id = WILAB_CLOSED_LOOP.task_source(i);
    out(k).helper_id = WILAB_CLOSED_LOOP.task_helper(i);
    out(k).required_packets = req(i);
    out(k).received_packets = WILAB_CLOSED_LOOP.task_received(i);
    ep = WILAB_CLOSED_LOOP.task_complete_epoch(i);
    out(k).complete = ~isnan(ep);
    if ~isnan(ep)
        out(k).complete_epoch = ep;
        out(k).complete_time_s = WILAB_CLOSED_LOOP.task_complete_time(i);
    end
    out(k).cancelled = WILAB_CLOSED_LOOP.task_cancelled(i);
    if i <= size(WILAB_CLOSED_LOOP.task_pending_bits,1)
        out(k).pending_units = sum(WILAB_CLOSED_LOOP.task_pending_bits(i, :));
    end
    dl = WILAB_CLOSED_LOOP.task_deadline_s(i);
    if isfinite(dl), out(k).deadline_s = dl; end
    out(k).overflow_losses = WILAB_CLOSED_LOOP.pkt_overflow_losses;
    out(k).tag_deficits = WILAB_CLOSED_LOOP.pkt_tag_deficits;
    out(k).capture_missing = WILAB_CLOSED_LOOP.pkt_capture_missing;
    out(k).paced_packets = WILAB_CLOSED_LOOP.pkt_paced;
    out(k).retransmitted_packets = WILAB_CLOSED_LOOP.pkt_retransmitted;
    out(k).cancelled_packets = WILAB_CLOSED_LOOP.pkt_cancelled;
    out(k).dropped_packets = WILAB_CLOSED_LOOP.pkt_dropped;
end
end

% -------------------------------------------------------------------------
function c = ensure_cell(c, n)
if numel(c) < n
    c{n} = [];
end
end

function v = ensure_vec(v, n, fill)
v = v(:);
if numel(v) < n
    v(end+1:n,1) = fill;
end
end
